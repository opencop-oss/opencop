CREATE SCHEMA IF NOT EXISTS TAKSERVER;

CREATE TABLE IF NOT EXISTS takserver.info (
    ID VARCHAR(255) PRIMARY KEY,
    MISSION VARCHAR(255) NOT NULL,
    CREDENTIALS_METHOD VARCHAR(255) NOT NULL,
    CONNECTION_FLAG BOOLEAN NOT NULL,
    ADDED_BY VARCHAR(255) NOT NULL,
    ADDED_TIMESTAMP TIMESTAMP NOT NULL,
    CLOUD_PROVIDER VARCHAR(255) NOT NULL
);